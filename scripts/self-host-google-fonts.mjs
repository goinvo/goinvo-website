#!/usr/bin/env node
/**
 * Mirrors the site's global Google Fonts (Open Sans, Montserrat) into public/fonts/google and
 * writes src/app/fonts.css with the same @font-face rules Google serves to Chrome: same family
 * names, weights, unicode-range subsets and font-display, only the URLs point at our origin.
 *
 * Why: loading them from Google costs two extra origins (fonts.googleapis.com for the CSS, then
 * fonts.gstatic.com for the files) on every page, which on a phone connection is several round
 * trips before text can use them. The family names stay "Open Sans" and "Montserrat", so the
 * ported per-page stylesheets that name them keep working. Both fonts are SIL OFL licensed.
 *
 * Usage: node scripts/self-host-google-fonts.mjs   (re-run to pick up new Google versions)
 */
import fs from 'node:fs'
import path from 'node:path'

const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Montserrat:wght@400;600;700;800&family=Open+Sans:wght@400;600&display=swap'
// Google picks the format by user agent; a current Chrome gets woff2 with unicode-range subsets.
const USER_AGENT =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/148.0.0.0 Safari/537.36'
const FONT_DIR = 'public/fonts/google'
const CSS_OUT = 'src/app/fonts.css'

const css = await (await fetch(CSS_URL, { headers: { 'user-agent': USER_AGENT } })).text()
const urls = [...new Set([...css.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g)].map((m) => m[1]))]
if (urls.length === 0) throw new Error('No font URLs in the Google CSS; the response format changed')

fs.mkdirSync(FONT_DIR, { recursive: true })
let rewritten = css
for (const url of urls) {
  // .../s/montserrat/v31/JTUSjIg1_i6t8kCHKm459Wlhyw.woff2 -> montserrat-v31-JTUSjIg1_i6t8kCHKm459Wlhyw.woff2
  const parts = new URL(url).pathname.match(/^\/s\/([^/]+)\/([^/]+)\/(.+)$/)
  if (!parts) throw new Error(`Unexpected font URL shape: ${url}`)
  const [, family, version, file] = parts
  const name = `${family}-${version}-${file}`
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${res.status} fetching ${url}`)
  fs.writeFileSync(path.join(FONT_DIR, name), Buffer.from(await res.arrayBuffer()))
  rewritten = rewritten.replaceAll(url, `/fonts/google/${name}`)
}

const header = `/* Generated by scripts/self-host-google-fonts.mjs from ${CSS_URL}
   Same @font-face rules Google serves, with the files on our origin. Do not edit by hand. */\n`
fs.writeFileSync(CSS_OUT, header + rewritten)
console.log(`${urls.length} font files -> ${FONT_DIR}, ${css.match(/@font-face/g).length} @font-face rules -> ${CSS_OUT}`)
