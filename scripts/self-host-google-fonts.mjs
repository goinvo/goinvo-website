#!/usr/bin/env node
/**
 * Mirrors Google Fonts into public/fonts/google and writes @font-face stylesheets with the same
 * rules Google serves to Chrome: same family names, weights, unicode-range subsets and
 * font-display, only the URLs point at our origin.
 *
 * Why: loading them from Google costs two extra origins (fonts.googleapis.com for the CSS, then
 * fonts.gstatic.com for the files) on every page, which on a phone connection is several round
 * trips before text can use them. The family names stay the same, so the ported per-page
 * stylesheets that name them keep working. Every font here is SIL OFL licensed.
 *
 * Two sets:
 *   site  Open Sans and Montserrat, used on every page          -> src/app/fonts.css
 *   hand  Caveat, Patrick Hand and Kalam, for the hand-drawn    -> src/app/fonts-hand.css
 *         review mode (design-hand.css). Latin only: a font file is only fetched once a page
 *         uses it, and only the review mode does.
 *
 * Usage: node scripts/self-host-google-fonts.mjs [--only site|hand]   (re-run to pick up new versions)
 */
import fs from 'node:fs'
import path from 'node:path'

const JOBS = [
  {
    name: 'site',
    url: 'https://fonts.googleapis.com/css2?family=Montserrat:wght@400;600;700;800&family=Open+Sans:ital,wght@0,400;0,600;1,400;1,600&display=swap',
    out: 'src/app/fonts.css',
  },
  {
    name: 'hand',
    url: 'https://fonts.googleapis.com/css2?family=Caveat:wght@400..700&family=Kalam:wght@400;700&family=Patrick+Hand&display=swap',
    out: 'src/app/fonts-hand.css',
    subsets: ['latin'],
  },
]
// Google picks the format by user agent; a current Chrome gets woff2 with unicode-range subsets.
const USER_AGENT =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/148.0.0.0 Safari/537.36'
const FONT_DIR = 'public/fonts/google'

const only = process.argv.includes('--only') ? process.argv[process.argv.indexOf('--only') + 1] : null
fs.mkdirSync(FONT_DIR, { recursive: true })

for (const job of JOBS.filter((j) => !only || j.name === only)) {
  let css = await (await fetch(job.url, { headers: { 'user-agent': USER_AGENT } })).text()
  if (job.subsets) {
    // Each rule is preceded by a /* subset */ comment; keep only the subsets asked for.
    const blocks = css.split(/(?=\/\* [\w-]+ \*\/)/)
    css = blocks.filter((b) => job.subsets.includes(b.match(/^\/\* ([\w-]+) \*\//)?.[1])).join('')
  }
  const urls = [...new Set([...css.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g)].map((m) => m[1]))]
  if (urls.length === 0) throw new Error(`No font URLs in the Google CSS for ${job.name}; the response format changed`)

  let rewritten = css
  for (const url of urls) {
    // .../s/montserrat/v31/JTUSjIg1_i6t8kCHKm459Wlhyw.woff2 -> montserrat-v31-JTUSjIg1_i6t8kCHKm459Wlhyw.woff2
    const parts = new URL(url).pathname.match(/^\/s\/([^/]+)\/([^/]+)\/(.+)$/)
    if (!parts) throw new Error(`Unexpected font URL shape: ${url}`)
    const [, family, version, file] = parts
    const name = `${family}-${version}-${file}`
    const res = await fetch(url)
    if (!res.ok) throw new Error(`${res.status} fetching ${url}`)
    fs.writeFileSync(path.join(FONT_DIR, name), Buffer.from(await res.arrayBuffer()))
    rewritten = rewritten.replaceAll(url, `/fonts/google/${name}`)
  }

  const header = `/* Generated by scripts/self-host-google-fonts.mjs from ${job.url}
   Same @font-face rules Google serves, with the files on our origin. Do not edit by hand. */\n`
  fs.writeFileSync(job.out, header + rewritten)
  console.log(`${job.name}: ${urls.length} font files -> ${FONT_DIR}, ${rewritten.match(/@font-face/g).length} @font-face rules -> ${job.out}`)
}
